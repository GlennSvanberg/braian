#!/usr/bin/env node
// Regenerate THIRD_PARTY_NOTICES.md.
// Needs `cargo license` (cargo-license) and `pnpm install`.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))

function run(command, args) {
  return execFileSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  })
}

const rust = JSON.parse(
  run('cargo', ['license', '--json', '--avoid-dev-deps', '--avoid-build-deps']),
)
  .filter((crate) => !crate.name.startsWith('braian-'))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const jsGrouped = JSON.parse(run('pnpm', ['licenses', 'list', '--prod', '--json', '--long']))
const js = []
for (const entries of Object.values(jsGrouped)) {
  if (!Array.isArray(entries)) continue
  for (const entry of entries) {
    if (entry.name === 'braian' || entry.name.startsWith('@braian/')) continue
    js.push(entry)
  }
}
js.sort((a, b) => a.name.localeCompare(b.name) || String(a.license).localeCompare(String(b.license)))

function rustLine(crate) {
  const repo = crate.repository ? ` — ${crate.repository}` : ''
  return `- \`${crate.name}\` ${crate.version} — ${crate.license}${repo}`
}

function jsLine(entry) {
  const versions = Array.isArray(entry.versions) ? entry.versions.join(', ') : ''
  const home = entry.homepage ? ` — ${entry.homepage}` : ''
  return `- \`${entry.name}\` ${versions} — ${entry.license}${home}`
}

const body = `# Third-party notices

Generated by \`node scripts/third-party-notices.mjs\`. Rust crates come from cargo-license (\`cargo license --json --avoid-dev-deps --avoid-build-deps\`). JavaScript packages are production dependencies from \`pnpm licenses list --prod --json --long\`. Workspace packages are omitted.

Braian talks to the services below over the network. They run as separate official upstream images and are not distributed with Braian.

## Infrastructure

| Component | Version | License | Source |
| --- | --- | --- | --- |
| Postgres | 18 | PostgreSQL License | [Licence](https://www.postgresql.org/about/licence/), [COPYRIGHT](https://github.com/postgres/postgres/blob/REL_18_STABLE/COPYRIGHT). Image \`postgres:18\` in \`compose.yaml\`. |
| Typesense | 30.2 | GPL-3.0 | [LICENSE.txt](https://github.com/typesense/typesense/blob/v30.2/LICENSE.txt). Image \`typesense/typesense:30.2\`. |

## Rust


${rust.map(rustLine).join('\n')}

## JavaScript

Production dependencies only.

${js.map(jsLine).join('\n')}
`

writeFileSync(new URL('../THIRD_PARTY_NOTICES.md', import.meta.url), body.endsWith('\n') ? body : `${body}\n`)
console.log(`Wrote THIRD_PARTY_NOTICES.md (${rust.length} Rust crates, ${js.length} JavaScript packages).`)
